                                            RelativeLocation(
                                                7.794229,
                                                0.0,
                                                -4.5
                                            )
                                        )
                                )
                        )
                )
                .createWithCompositionData { rel ->
                    CompositionData()
                        .setDisplayerSupplier {
                            ParticleDisplayer.withCParticle(it, CParticleRenderLayer.ADDITION_BLEND_TRANSLUCENT_NOT_HDR)
