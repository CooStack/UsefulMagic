    }

    override fun remove() {
        if (status.isDisable()) {
            super.remove()
        } else {
            status.disable()
        }
    }

    override fun onDisplay() {
        addPreTickAction {
            if (status.isDisable()) {
                playCParticleAlphaTransition(30f, CParticleCurve.linear(1f, 0f))
            } else {
                playCParticleAlphaTransition(30f, CParticleCurve.linear(0f, 1f))
            }
            rotateToWithAngle(direction, PI / 16)
        }
    }
